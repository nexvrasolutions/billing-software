
/*
 * Service worker updates with open (offline) tabs (M-19)
 * (NO DATABASE, NO SERVER, NO NETWORK, NO BROWSER: source and build-output
 * checks only).
 *
 * - next.config.ts: a new worker waits (skipWaiting: false) instead of taking
 *   over open tabs; pages are not reloaded on reconnect.
 * - public/sw.js (output of the LAST production build): no unconditional
 *   skipWaiting, a SKIP_WAITING message listener, clientsClaim for the first
 *   install, the offline pages precached, /api never cached, no dev worker.
 * - UpdateBanner: announces only real updates, activates the waiting worker
 *   only when the user asks, and never deletes caches, storage or queue
 *   items, or unregisters the worker.
 *
 * public/sw.js is regenerated by "npm run build" (and replaced by a
 * development worker if "npm run dev" runs). This checks the file on disk;
 * it does NOT prove how a browser installs or updates the worker.
 *
 * Run (from the project root):
 *   npx tsx scripts/test-sw-update.ts
 */

import { readFileSync } from "node:fs";
import path from "node:path";

const results: { name: string; passed: boolean; detail?: string }[] = [];

function check(name: string, condition: boolean, detail?: string) {
    results.push({ name, passed: condition, detail: condition ? undefined : detail });
    console.log(`${condition ? "PASS" : "FAIL"}  ${name}${!condition && detail ? `  -> ${detail}` : ""}`);
}

const read = (file: string) => readFileSync(path.join(process.cwd(), file), "utf8");
const config = read("next.config.ts");
const sw = read("public/sw.js");
const banner = read("components/offline/UpdateBanner.tsx");
const layout = read("app/layout.tsx");

// ------------------------------------------------------------ configuration
check("C1. A new service worker waits instead of taking over open tabs", /skipWaiting: false,/.test(config));
check("C2. Pages are not reloaded automatically on reconnect", /reloadOnOnline: false,/.test(config));
check("C3. The offline pages stay precached and /api stays network-only",
    /\{ url: "\/dashboard", revision: APP_SHELL_REVISION \}/.test(config) && /\{ url: "\/offline-test", revision: APP_SHELL_REVISION \}/.test(config)
    && /handler: "NetworkOnly"/.test(config));

// ------------------------------------------------------------ generated worker (last build)
check("W1. The built worker is the production one (no development worker)", !sw.includes("worker-development") && /workbox-[a-f0-9]+/.test(sw));
check("W2. No unconditional skipWaiting() in the built worker", !/self\.skipWaiting\(\)\s*[,;]/.test(sw));
check("W3. The built worker activates only on a SKIP_WAITING message",
    /self\.addEventListener\("message",\w+=>\{\w+\.data&&"SKIP_WAITING"===\w+\.data\.type&&self\.skipWaiting\(\)\}\)/.test(sw));
check("W4. The first install still controls the page at once (clientsClaim)", /\.clientsClaim\(\)/.test(sw));
check("W5. /dashboard and /offline-test are precached; /api requests are network-only",
    sw.includes('url:"/dashboard"') && sw.includes('url:"/offline-test"') && /startsWith\("\/api\/"\),new \w+\.NetworkOnly/.test(sw));

// ------------------------------------------------------------ the update notice
check("U1. Only an update is announced (a worker installed while the page is already controlled)",
    /worker && navigator\.serviceWorker\.controller\) setWaiting\(worker\)/.test(banner)
    && /installing\.state === "installed"/.test(banner) && /offer\(registration\.waiting\)/.test(banner));
const update = banner.slice(banner.indexOf("function update()"), banner.indexOf("return (", banner.indexOf("function update()")));
check("U2. The waiting worker is activated only from the user's \"Reload to update\" click",
    (banner.match(/postMessage\(\{ type: "SKIP_WAITING" \}\)/g) ?? []).length === 1 && update.includes("postMessage")
    && /onClick=\{update\}/.test(banner));
check("U3. The page reloads only after the new worker controls it",
    /addEventListener\("controllerchange", \(\) => window\.location\.reload\(\), \{ once: true \}\)/.test(update));
check("U4. The notice never deletes caches, storage or queue items, or unregisters the worker",
    !/caches\.|unregister\(|indexedDB|offlineDB|localStorage|\.clear\(|\.delete\(/.test(banner));
check("U5. The notice tells the user to finish the current sale and that waiting operations stay",
    /Finish the sale you are entering/.test(banner) && /Waiting operations stay on this device/.test(banner));
check("U6. The root layout shows the notice on every page, once",
    (layout.match(/<UpdateBanner \/>/g) ?? []).length === 1);

const failed = results.filter((r) => !r.passed);
console.log(`\n${results.length - failed.length}/${results.length} checks passed.`);
failed.forEach((f) => console.log(`  - ${f.name}${f.detail ? `: ${f.detail}` : ""}`));
process.exitCode = failed.length ? 1 : 0;
